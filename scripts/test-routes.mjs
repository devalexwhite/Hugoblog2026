import assert from 'node:assert/strict';
import { readFileSync, mkdtempSync, cpSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
const source = readFileSync('themes/quiet-ink/static/js/routes.js', 'utf8');
const { statistics } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const a = {lat:0, lon:0, time:0}, b = {lat:0, lon:1, time:3600000};
const stats = statistics([[a,b]]);
assert.ok(Math.abs(stats.distance - 111.195) < .01);
assert.equal(stats.speed, stats.distance);
assert.equal(statistics([[a], [b]]).distance, 0, 'Do not bridge segments');
assert.equal(statistics([[a, {...b,time:NaN}]]).speed, null);
assert.equal(statistics([[a, {...b,time:0}]]).speed, null);
assert.equal(statistics([[b,a]]).speed, null);
assert.ok(statistics([[{...a,lon:179.9},{...b,lon:-179.9}]]).distance < 23);
// Build a separate site so fixtures never become published personal rides.
const root = mkdtempSync(join(tmpdir(), 'cycling-routes-'));
for (const dir of ['themes','content','assets','data','static','resources']) cpSync(dir,join(root,dir),{recursive:true});
cpSync('hugo.toml',join(root,'hugo.toml'));
for (const name of ['one.gpx','two.GPX','three.gpx','four.gpx']) writeFileSync(join(root,'static/routes',name), '<gpx><trk><trkseg><trkpt lat="0" lon="0"/><trkpt lat="0" lon="1"/></trkseg></trk></gpx>');
writeFileSync(join(root,'data/cycling_routes.json'),JSON.stringify({'two.GPX':{favorite:true,title:'A favorite',country:'United States'}}));
execFileSync('hugo',['--source',root,'--panicOnWarning'],{stdio:'pipe'});
const html=readFileSync(join(root,'public/cycling/index.html'),'utf8');
assert.equal((html.match(/class="route-card"/g)||[]).length,4);
assert.match(html,/data-favorite="true"/);
assert.match(html,/A favorite/);
assert.match(html,/United States/);
assert.match(html,/routes\/two.GPX/);
console.log('PASS: distance, timestamps, segment gaps, antimeridian, GPX discovery, favorites, and metadata.');
